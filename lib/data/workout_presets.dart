enum WorkoutPresetGoal { hypertrophy, strength, hybrid }

class WorkoutPreset {
  final String id;
  final int version;
  final String name;
  final String installName;
  final WorkoutPresetGoal goal;
  final String splitStyle;
  final String bestFit;
  final String duration;
  final String summary;
  final String schedule;
  final List<int?> scheduleSlots;
  final List<WorkoutPresetPlan> plans;

  const WorkoutPreset({
    required this.id,
    required this.version,
    required this.name,
    required this.installName,
    required this.goal,
    required this.splitStyle,
    required this.bestFit,
    required this.duration,
    required this.summary,
    required this.schedule,
    required this.scheduleSlots,
    required this.plans,
  });

  int get days => plans.length;
}

class WorkoutPresetPlan {
  final String name;
  final int colorSlot;
  final List<WorkoutPresetExercise> exercises;

  const WorkoutPresetPlan({
    required this.name,
    required this.colorSlot,
    required this.exercises,
  });
}

class WorkoutPresetExercise {
  final String name;
  final String prescription;
  final List<int> seedReps;
  final String rir;
  final String rest;

  const WorkoutPresetExercise({
    required this.name,
    required this.prescription,
    required this.seedReps,
    required this.rir,
    required this.rest,
  });

  String? get note {
    if (seedReps.length == 3 &&
        seedReps[0] == 1 &&
        seedReps[1] == 3 &&
        seedReps[2] == 5) {
      return 'Heavy practice single—not a max. Reduce the load for 3 reps, '
          'then reduce it again for 5.';
    }
    if (name == 'Pull-ups' || name == 'Chin-ups' || name == 'Push-ups') {
      return 'Enter only added load; bodyweight is not included.';
    }
    return null;
  }

  List<String> get substitutions =>
      workoutPresetSubstitutions[name] ?? const <String>[];

  ExerciseTemplate toTemplate() => ExerciseTemplate(
    name: name,
    sets: seedReps.length,
    note: note,
    setTargets: [
      for (final reps in seedReps) SetTemplate(reps: reps, weight: 0),
    ],
  );
}

