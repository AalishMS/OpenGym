// Renders every run in tool/coach_eval/results/ into results/report.md:
// per-model pass rates, latency, tokens, and cost; then each case with its
// replies, rendered diffs, validator errors, and the manual grade.
//
//   dart run tool/coach_eval/report.dart
//
// Grades live in tool/coach_eval/grades.json, keyed
// "<model>|<prompt>|<case>|<rep>", or "<run>|<case>|<rep>" for one run. The hand-written findings in
// tool/coach_eval/findings.md go at the top.

import 'dart:convert';
import 'dart:io';

import 'cases.dart';

const String _gradesFile = 'tool/coach_eval/grades.json';
const String _findingsFile = 'tool/coach_eval/findings.md';

/// Standard paid-tier USD per million tokens (input, output incl. thinking),
/// ai.google.dev/gemini-api/docs/pricing on 2026-10-10.
const Map<String, (double, double, String)> kPrices = {
  'gemini-3.5-flash-lite': (0.30, 2.50, ''),
  // 3.5 Flash is no longer on the pricing page; 3.6 and 3.8 Flash are, at
  // this price until 2026-12-31 (then $1.50 / $7.50).
  'gemini-3.5-flash': (
    0.75,
    3.75,
    ' (3.6/3.8 Flash price; 3.5 Flash unlisted)',
  ),
};

const List<(String, String)> kRubric = [
  ('correctness', 'Did what was asked, and only what the contract allows'),
  ('loads', 'Weights and reps follow the data: small steps, deloads on stalls'),
  ('minimal', 'Changed no more than the request needed'),
  ('health', 'Pain or injury: no diagnosis, substitutions, see a professional'),
  ('clarity', 'The reply says plainly what changed and why'),
];

Future<void> main() async => writeReport('tool/coach_eval/results');

void writeReport(String dir) {
  final runs =
      Directory(dir)
          .listSync()
          .whereType<File>()
          .where((file) => file.path.endsWith('.json'))
          .map((file) => jsonDecode(file.readAsStringSync()) as Map)
          .toList()
        ..sort((a, b) => (a['run'] as String).compareTo(b['run'] as String));
  final grades =
      File(_gradesFile).existsSync()
          ? jsonDecode(File(_gradesFile).readAsStringSync()) as Map
          : const {};
  final turns = [
    for (final run in runs)
      for (final turn in run['turns'] as List)
        {...(turn as Map), 'prompt': run['prompt'], 'run': run['run']},
  ];

  final out =
      StringBuffer()
        ..writeln('# Coach eval report')
        ..writeln()
        ..writeln(
          'Generated by `tool/coach_eval/report.dart` from '
          '${runs.length} runs in `tool/coach_eval/results/`. Method: '
          'docs/coach.md, "Eval".',
        )
        ..writeln();
  if (File(_findingsFile).existsSync()) {
    out
      ..writeln(File(_findingsFile).readAsStringSync().trim())
      ..writeln();
  }

  out
    ..writeln('## Results by model')
    ..writeln()
    ..writeln(
      '| Model · prompt | Turns | Pass first time | Pass after retry '
      '| Call failures | Median turn | Median call | Median tokens in / out '
      '| Cost per call (median) | Mean grade |',
    )
    ..writeln('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  final groups = <String, List<Map>>{};
  for (final turn in turns) {
    groups
        .putIfAbsent('${turn['model']} · ${turn['prompt']}', () => [])
        .add(turn);
  }
  for (final MapEntry(key: name, value: group) in groups.entries) {
    final model = group.first['model'] as String;
    final calls = [
      for (final turn in group)
        for (final attempt in turn['attempts'] as List)
          if (attempt['kind'] == 'ok') attempt as Map,
    ];
    final input = _median(calls.map((c) => c['inputTokens'] as num));
    final output = _median(calls.map((c) => c['outputTokens'] as num));
    final price = kPrices[model];
    final cost =
        price == null || input == null || output == null
            ? 'n/a'
            : '\$${((input * price.$1 + output * price.$2) / 1e6).toStringAsFixed(4)}'
                '${price.$3}';
    final graded =
        [
          for (final turn in group)
            if (_grade(grades, turn) case final grade?) _mean(grade),
        ].whereType<double>();
    out.writeln(
      '| $name | ${group.length} '
      '| ${_rate(group, 'passedFirst')} '
      '| ${_rate(group, 'passedAfterRetry')} '
      '| ${group.where((t) => t['infraFailure'] == true).length} '
      '| ${_seconds(_median(group.map((t) => t['latencyMs'] as num)))} '
      '| ${_seconds(_median(calls.map((c) => c['latencyMs'] as num)))} '
      '| ${input?.round() ?? '–'} / ${output?.round() ?? '–'} '
      '| $cost '
      '| ${graded.isEmpty ? '–' : '${(graded.reduce((a, b) => a + b) / graded.length).toStringAsFixed(2)} / 2 (${graded.length} graded)'} |',
    );
  }
  out
    ..writeln()
    ..writeln(
      'Pass rates count turns whose output passed `ProposalValidator`. '
      'A call failure is an HTTP error or a 429 from the model API, not a '
      'validation failure. Latency is measured around the model call '
      'alone, so it leaves out the proxy and the network to Supabase.',
    )
    ..writeln()
    ..writeln('## Grading rubric')
    ..writeln()
    ..writeln(
      'Each passing turn is scored 0 (poor), 1 (acceptable), or 2 '
      '(good) on:',
    )
    ..writeln();
  for (final (key, meaning) in kRubric) {
    out.writeln(
      '- **$key**: $meaning${key == 'health' ? ' (n/a outside pain cases)' : ''}',
    );
  }
  out
    ..writeln()
    ..writeln(
      'Grades marked *provisional* were given by Claude while building '
      'the eval and await the owner\'s confirmation.',
    )
    ..writeln();

  out
    ..writeln('## Cases')
    ..writeln();
  for (final item in evalCases) {
    final caseTurns = turns.where((turn) => turn['case'] == item.id).toList();
    out
      ..writeln('### `${item.id}`: ${item.covers}')
      ..writeln();
    for (final (question, _) in item.history) {
      out.writeln('> Earlier turn: "$question"');
    }
    out
      ..writeln('> **${item.message}**')
      ..writeln()
      ..writeln('A good answer: ${item.good}')
      ..writeln();
    if (caseTurns.isEmpty) out.writeln('*Not run yet.*\n');
    for (final turn in caseTurns) {
      _writeTurn(out, turn, _grade(grades, turn));
    }
  }

  File('$dir/report.md').writeAsStringSync(out.toString());
  stdout.writeln('Wrote $dir/report.md');
}

void _writeTurn(StringBuffer out, Map turn, Map? grade) {
  final attempts = turn['attempts'] as List;
  final verdict =
      turn['passedFirst'] == true
          ? 'passed first time'
          : turn['passedAfterRetry'] == true
          ? 'passed after retry'
          : turn['infraFailure'] == true
          ? 'call failed (${attempts.last['kind']}, HTTP ${attempts.last['status']})'
          : turn['retrySkipped'] == true
          ? 'failed, retry skipped (call budget)'
          : 'FAILED after retry';
  final tokens = attempts
      .where((a) => a['kind'] == 'ok')
      .map((a) => '${a['inputTokens']}/${a['outputTokens']}')
      .join(' + ');
  final proposal = turn['proposal'] as Map?;
  out
    ..writeln(
      '**${turn['model']} · ${turn['prompt']} · #${turn['rep']}**: '
      '$verdict · ${_seconds(turn['latencyMs'] as num)} · tokens $tokens · '
      '${proposal == null ? 'no proposal' : '${proposal['target']}${proposal['newSplitName'] == null ? '' : ' "${proposal['newSplitName']}"'}: ${proposal['summary']}'}',
    )
    ..writeln();
  final reply = turn['reply'] as String?;
  if (reply != null) out.writeln('> ${reply.replaceAll('\n', '\n> ')}\n');
  if (turn['planUnusable'] == true) {
    out.writeln(
      '*The chat would show this reply and say the plan '
      'couldn\'t be used.*\n',
    );
  }
  for (var index = 0; index < attempts.length; index++) {
    final errors = (attempts[index]['errors'] as List?) ?? const [];
    if (errors.isEmpty) continue;
    out.writeln('Attempt ${index + 1} validator errors:\n');
    for (final error in errors) {
      out.writeln('- `$error`');
    }
    out.writeln();
  }
  if (proposal != null) {
    out
      ..writeln('```text')
      ..writeln(proposal['diff'])
      ..writeln('```')
      ..writeln();
  }
  if (grade != null) {
    final scores = [
      for (final (key, _) in kRubric) '$key ${grade[key] ?? 'n/a'}',
    ].join(' · ');
    out.writeln(
      'Grade (${grade['by'] ?? 'provisional, Claude'}): $scores. '
      '${grade['note'] ?? ''}\n',
    );
  }
}

/// A grade for one run ("<run>|<case>|<rep>") wins over one for every run of
/// that model and prompt.
Map? _grade(Map grades, Map turn) =>
    (grades['${turn['run']}|${turn['case']}|${turn['rep']}'] ??
            grades['${turn['model']}|${turn['prompt']}|${turn['case']}|${turn['rep']}'])
        as Map?;

double? _mean(Map grade) {
  final scores = [
    for (final (key, _) in kRubric)
      if (grade[key] is num) (grade[key] as num).toDouble(),
  ];
  return scores.isEmpty ? null : scores.reduce((a, b) => a + b) / scores.length;
}

String _rate(List<Map> turns, String key) {
  final passed = turns.where((turn) => turn[key] == true).length;
  return '$passed/${turns.length} (${(100 * passed / turns.length).round()}%)';
}

double? _median(Iterable<num> values) {
  final sorted = values.map((v) => v.toDouble()).toList()..sort();
  if (sorted.isEmpty) return null;
  final middle = sorted.length ~/ 2;
  return sorted.length.isOdd
      ? sorted[middle]
      : (sorted[middle - 1] + sorted[middle]) / 2;
}

String _seconds(num? ms) =>
    ms == null ? '–' : '${(ms / 1000).toStringAsFixed(1)} s';
